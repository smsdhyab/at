-- السرير الثالث: الطفل من 6 سنوات فأكثر يحوّل الغرفة المزدوجة إلى ثلاثية،
-- والفندق يتقاضى فرقاً عن السرير الإضافي. عمود مستقل لأن الفرق يختلف بين
-- فندق وآخر ولا يُشتقّ من سعر الغرفة بنسبة ثابتة.
alter table hotels add column if not exists rate_triple integer not null default 0;

-- قيمة ابتدائية معقولة: 35٪ من سعر الغرفة العادي، مقرّبة لأقرب دولار.
-- عدّلها من البوت بأسعار موردك الحقيقية.
update hotels
   set rate_triple = round(rate_normal * 0.35 / 100.0) * 100
 where rate_triple = 0;
