-- ═══ إسطنبول: جولة جزيرة الأميرات بدل رحلة القارب ═══
--
-- بطلب المالك: تُستبدل «رحلة البوسفور بالقارب» بجولة جزيرة الأميرات كاملة اليوم.
-- السعر 100$ = يوم سيارة داخل إسطنبول حسب ورقة المواصلات (2026-09-07)، لأن
-- السيارة تعمل طوال اليوم: من الفندق إلى الميناء، ثم بعد العودة للتسوق والعشاء.

update tours set active = false
where destination = 'istanbul' and name like 'رحلة البوسفور%';

update tours
set name = 'جولة جزيرة الأميرات',
    price = 10000,
    sort_order = (select coalesce(min(sort_order), 2) from tours where destination = 'istanbul' and name like 'رحلة البوسفور%'),
    description = 'انطلاق بالسيارة من الفندق إلى ميناء القوارب، ثم الإبحار إلى جزيرة الأميرات حيث لا سيارات: تجوال بين البيوت الخشبية والمقاهي المطلة على البحر. بعد العودة إلى إسطنبول جولة تسوق وعشاء، ثم العودة إلى الفندق.'
where destination = 'istanbul' and name like 'جزر الأميرات%';

